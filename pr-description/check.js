// Fails a PR whose description is over the length limit.

const SKIPPED = ['decisions', 'precedent', 'reviewer notes']
const BOILERPLATE = /^(_Requested by \*\*|🤖 Generated with|_Generated by \[Claude Code\]|https:\/\/claude\.ai\/code\/\S+$|---$)/
const FOOTER = /<!--\s*([\w-]+):footer\s*-->[\s\S]*?<!--\s*\/\1:footer\s*-->/g

// The part of a description that counts: no HTML comments, bot footers,
// attribution lines, or Decisions, Precedent and Reviewer notes sections.
function countedText (body) {
  const text = (body || '').replace(/\r\n/g, '\n').replace(FOOTER, '').replace(/<!--[\s\S]*?-->/g, '')
  const kept = []
  let fence = ''
  let skipLevel = 0
  for (const line of text.split('\n')) {
    const run = line.match(/^\s{0,3}(`{3,}|~{3,})(.*)$/)
    if (run && !fence && !(run[1][0] === '`' && run[2].includes('`'))) fence = run[1]
    else if (run && fence && run[1][0] === fence[0] && run[1].length >= fence.length && !run[2].trim()) fence = ''
    const fenced = fence || run
    const heading = !fenced && line.match(/^(#{1,6})\s+(.*)$/)
    if (heading) {
      const level = heading[1].length
      if (skipLevel && level <= skipLevel) skipLevel = 0
      if (!skipLevel && SKIPPED.some((name) => heading[2].trim().toLowerCase().startsWith(name))) skipLevel = level
    }
    if (!skipLevel && !BOILERPLATE.test(line.trim())) kept.push(line)
  }
  return kept.join('\n').trim()
}

async function check ({ github, context, core, limit }) {
  const pr = context.payload.pull_request
  let body = pr.body
  let live = true
  try {
    const request = { signal: AbortSignal.timeout(30000) }
    body = (await github.rest.pulls.get({ ...context.repo, pull_number: pr.number, request })).data.body
  } catch (err) {
    live = false
    const hint = [403, 404].includes(err.status) ? ' Grant pull-requests: read so a re-run sees edits.' : ''
    core.warning(`Couldn't read the current PR description (${err.message}); checking the one from the triggering event.${hint}`)
  }
  const text = countedText(body)
  if (text.startsWith('> **Reference PR')) return core.info('Mikado reference PR, skipping.')
  const chars = [...text].length
  core.info(`PR description is ${chars} characters; the limit is ${limit}.`)
  if (chars > limit) {
    const recheck = live ? 're-run this job' : 'push a commit to re-check'
    core.setFailed(`PR description is ${chars} characters, not counting boilerplate, Decisions, Precedent or Reviewer notes; the limit is ${limit}. Shorten it, then ${recheck}.`)
  }
}

module.exports = { countedText, check }
